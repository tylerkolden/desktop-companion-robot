"""Draw exact 128x64 monochrome faces; generate Arduino bitmaps and a preview.

Edit these pixel coordinates, then run this script. The preview and firmware
use the SAME pixels, so no separately maintained illustration can drift.
Requires Pillow (also used by build_wiring.py).
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
NAMES = ['awake', 'happy', 'sleep', 'curious', 'surprised', 'love', 'cheeky']

def face(name):
    im = Image.new('1', (128, 64))
    d = ImageDraw.Draw(im)
    def eye(x, y=23):
        d.ellipse((x-10,y-10,x+10,y+10), fill=1)
        d.ellipse((x-3,y-4,x+3,y+4), fill=0)
        d.point((x-2,y-3), fill=1)
    def smile():
        d.arc((47,31,81,48), 0, 180, fill=1, width=2)
    if name == 'awake':
        eye(38); eye(90); smile()
    elif name == 'happy':
        for x in (38,90):
            d.arc((x-10,15,x+10,31),180,360,fill=1,width=3)
        d.ellipse((47,34,81,49),fill=1)
        d.rectangle((47,33,81,39),fill=0)
        d.line((52,40,76,40),fill=1,width=2)
    elif name == 'sleep':
        for x in (38,90):
            d.arc((x-10,16,x+10,27),0,180,fill=1,width=2)
        d.ellipse((60,39,68,48),outline=1,width=2)
        d.text((106,4),'z',fill=1)
        d.text((117,0),'Z',fill=1)
    elif name == 'curious':
        eye(38); eye(90,26)
        d.line((25,8,47,5),fill=1,width=2)
        d.line((80,12,99,15),fill=1,width=2)
        d.line((51,45,74,41),fill=1,width=2)
        d.text((112,9),'?',fill=1)
    elif name == 'surprised':
        for x in (38,90):
            eye(x)
            d.line((x-8,7,x+8,7),fill=1,width=2)
        d.ellipse((57,37,71,50),outline=1,width=3)
    elif name == 'love':
        for x in (38,90):
            d.ellipse((x-11,13,x+1,25),fill=1)
            d.ellipse((x-1,13,x+11,25),fill=1)
            d.polygon([(x-11,21),(x+11,21),(x,34)],fill=1)
        smile()
        for x in (27,95):
            d.line((x,37,x+6,37),fill=1,width=2)
    elif name == 'cheeky':
        eye(38)
        d.line([(79,19),(90,25),(101,19)],fill=1,width=3)
        smile()
        d.rounded_rectangle((64,42,75,51),radius=4,fill=1)
        d.line((69,45,69,49),fill=0)
    # The tiny triangle is our robot's nose. All faces have eyes and a mouth.
    d.line([(64,28),(61,33),(66,33)],fill=1,width=1)
    font=ImageFont.load_default()
    label=name.upper()
    box=d.textbbox((0,0),label,font=font)
    d.text(((128-(box[2]-box[0]))//2,53),label,font=font,fill=1)
    return im

def main():
    faces=[face(n) for n in NAMES]
    header=['// Generated by scripts/build_faces.py; edit the pixel drawings there.',
            '#pragma once', '#include <pgmspace.h>', 'namespace lesson {',
            'constexpr int FACE_COUNT=7;',
            'inline const char *faceName(int n) {',
            '  static const char *names[]={"AWAKE","HAPPY","SLEEP","CURIOUS","SURPRISED","LOVE","CHEEKY"};',
            '  return n>=0 && n<FACE_COUNT ? names[n] : "CLEAR";', '}',
            'const uint8_t FACE_BITMAPS[FACE_COUNT][1024] PROGMEM = {']
    for name,im in zip(NAMES,faces):
        data=im.tobytes()  # row-major, MSB first: Adafruit_GFX drawBitmap format
        assert len(data)==1024
        header.append('  { // '+name)
        for i in range(0,len(data),16):
            header.append('    '+','.join(f'0x{x:02x}' for x in data[i:i+16])+',')
        header.append('  },')
    header+=['};','}']
    (ROOT/'lessons/lib/RobotLessons/src/FaceArt.h').write_text('\n'.join(header)+'\n',encoding='utf-8')
    gallery=Image.new('RGB',(1120,340),'#172432')
    for i,im in enumerate(faces):
        gallery.paste(im.convert('RGB').resize((256,128),Image.Resampling.NEAREST),
                      (12+(i%4)*280,20+(i//4)*170))
    destination=ROOT/'docs/faces'
    destination.mkdir(exist_ok=True)
    gallery.save(destination/'face-gallery.png')
    print('Generated seven 128x64 face bitmaps and matching gallery.')

if __name__ == '__main__':
    main()

"""Draw exact 128x64 monochrome faces; generate Arduino bitmaps and a preview.

Edit these pixel coordinates, then run this script. The preview and firmware
use the SAME pixels, so no separately maintained illustration can drift.
Requires Pillow (also used by build_wiring.py).
"""
from pathlib import Path
from PIL import Image, ImageDraw
import math

ROOT = Path(__file__).resolve().parents[1]
NAMES = ['awake', 'happy', 'sleep', 'curious', 'surprised', 'cool', 'cheeky']

FRAME_MS = 100
FRAME_COUNT = 40

def face(name, frame=0):
    im = Image.new('1', (128, 64))
    d = ImageDraw.Draw(im)
    # A four-second loop sampled at 10 frames/sec. No text or nose.
    phase=frame/FRAME_COUNT
    wave=math.sin(phase*2*math.pi)
    blink=frame in (27,28)
    dx=round(5*math.sin(phase*2*math.pi)) if name in ('awake','curious') else 0
    dy=round(3*math.sin(phase*4*math.pi)) if name=='curious' else 0
    def eye(x, y=8, width=25, height=27):
        x+=dx; y+=dy
        if blink or (name=='surprised' and frame in (31,32)):
            y+=height//2-2; height=4
        d.rounded_rectangle((x,y,x+width,y+height),radius=min(10,height//2),fill=1)
    def smile():
        d.arc((42,30,86,57),0,180,fill=1,width=4)
    if name == 'awake':
        eye(19); eye(84); smile()
    elif name == 'happy':
        for x in (18,83):
            d.arc((x,9,x+28,35),180,360,fill=1,width=5)
        d.ellipse((42,27,86,59),fill=1)
        d.rectangle((41,26,87,40),fill=0)
        d.rounded_rectangle((59,48,72,58+round(3*wave)),radius=5,fill=1)
        d.line((65,51,65,55),fill=0,width=1)
    elif name == 'sleep':
        for x in (18,83):
            h=max(4,round(18*(1+wave)/2))
            d.arc((x,20-h//2,x+28,22+h//2),0,180,fill=1,width=4)
        d.arc((51,40,77,52+round(3*wave)),0,180,fill=1,width=3)
    elif name == 'curious':
        eye(19,13,25,19); eye(84,5,25,30)
        d.arc((48,35,84,54),10,155,fill=1,width=4)
    elif name == 'surprised':
        eye(19,5,25,30); eye(84,5,25,30)
        d.ellipse((54,40,74,60),fill=1)
    elif name == 'cool':
        eye(19); eye(84); smile()
        # Glasses enter from above, hold, then lift before the loop repeats.
        slide=round(-35*(1-min(1,frame/8,(39-frame)/7)))
        for x in (13,79):
            d.rounded_rectangle((x,8+slide,x+36,35+slide),radius=7,fill=1)
            d.rounded_rectangle((x+4,12+slide,x+32,30+slide),radius=4,fill=0)
            d.line((x+9,25+slide,x+20,16+slide),fill=1,width=2)
        d.line((49,15+slide,79,15+slide),fill=1,width=4)
    elif name == 'cheeky':
        eye(19)
        d.arc((83,11,111,33),180,360,fill=1,width=5)
        smile()
        d.rounded_rectangle((65,48,78,57+round(4*(1+wave)/2)),radius=5,fill=1)
    return im

def main():
    frames=[[face(n,f) for f in range(FRAME_COUNT)] for n in NAMES]
    # Deduplicate held frames: storage grows only when the pixels change.
    unique=[]; lookup={}; indices=[]
    for sequence in frames:
        row=[]
        for im in sequence:
            data=im.tobytes()
            assert len(data)==1024
            if data not in lookup:
                lookup[data]=len(unique); unique.append(data)
            row.append(lookup[data])
        indices.append(row)
    header=['// Generated by scripts/build_faces.py; edit animation drawings there.',
            '#pragma once', '#include <pgmspace.h>', 'namespace lesson {',
            'constexpr int FACE_COUNT=7;',
            f'constexpr uint32_t FACE_FRAME_MS={FRAME_MS};',
            f'constexpr int FACE_FRAMES={FRAME_COUNT};',
            'constexpr uint32_t FACE_LOOP_MS=FACE_FRAME_MS*FACE_FRAMES;',
            'constexpr int faceFrame(uint32_t age) { return (age/FACE_FRAME_MS)%FACE_FRAMES; }',
            'static_assert(faceFrame(99)==0 && faceFrame(100)==1 && faceFrame(4000)==0, "frame timing and wrap");',
            'inline const char *faceName(int n) {',
            '  static const char *names[]={"AWAKE","HAPPY","SLEEP","CURIOUS","SURPRISED","COOL","CHEEKY"};',
            '  return n>=0 && n<FACE_COUNT ? names[n] : "CLEAR";', '}',
            'const uint16_t FACE_SEQUENCE[FACE_COUNT][FACE_FRAMES] PROGMEM = {']
    header += ['  {'+','.join(map(str,row))+'},' for row in indices]
    header += ['};',f'const uint8_t FACE_BITMAPS[{len(unique)}][1024] PROGMEM = {{']
    for data in unique:
        header.append('  {')
        for i in range(0,len(data),16):
            header.append('    '+','.join(f'0x{x:02x}' for x in data[i:i+16])+',')
        header.append('  },')
    header+=['};','}']
    (ROOT/'lessons/lib/RobotLessons/src/FaceArt.h').write_text('\n'.join(header)+'\n',encoding='utf-8')
    def gallery_at(frame):
        gallery=Image.new('RGB',(1120,340),'#172432')
        for i,sequence in enumerate(frames):
            gallery.paste(sequence[frame].convert('RGB').resize((256,128),Image.Resampling.NEAREST),
                          (12+(i%4)*280,20+(i//4)*170))
        return gallery
    gallery=gallery_at(12)
    destination=ROOT/'docs/faces'
    destination.mkdir(exist_ok=True)
    gallery.save(destination/'face-gallery.png')
    previews=[gallery_at(f) for f in range(FRAME_COUNT)]
    previews[0].save(destination/'face-animations.gif',save_all=True,append_images=previews[1:],duration=FRAME_MS,loop=0,disposal=2)
    assert all(len(set(row))>1 for row in indices), 'Every face must animate'
    print(f'Generated seven four-second animations: {len(unique)} unique frames, {len(unique)*1024} bitmap bytes.')

if __name__ == '__main__':
    main()

"""Draw exact 128x64 monochrome faces; generate Arduino bitmaps and a preview.

Edit these pixel coordinates, then run this script. The preview and firmware
use the SAME pixels, so no separately maintained illustration can drift.
Requires Pillow (also used by build_wiring.py).
"""
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
NAMES = ['awake', 'happy', 'sleep', 'curious', 'surprised', 'love', 'cheeky']

def face(name):
    im = Image.new('1', (128, 64))
    d = ImageDraw.Draw(im)
    # Soft solid eyes, no staring pupils, noses, labels or decoration.
    def eye(x, y=8, width=25, height=27):
        d.rounded_rectangle((x,y,x+width,y+height),radius=10,fill=1)
    def smile():
        d.arc((42,30,86,57),0,180,fill=1,width=4)
    if name == 'awake':
        eye(19); eye(84); smile()
    elif name == 'happy':
        for x in (18,83):
            d.arc((x,9,x+28,35),180,360,fill=1,width=5)
        d.ellipse((42,27,86,59),fill=1)
        d.rectangle((41,26,87,40),fill=0)
    elif name == 'sleep':
        for x in (18,83):
            d.arc((x,9,x+28,31),0,180,fill=1,width=4)
        d.arc((51,40,77,54),0,180,fill=1,width=3)
    elif name == 'curious':
        eye(19,13,25,19); eye(84,5,25,30)
        d.arc((48,35,84,54),10,155,fill=1,width=4)
    elif name == 'surprised':
        eye(19,5,25,30); eye(84,5,25,30)
        d.ellipse((54,40,74,60),fill=1)
    elif name == 'love':
        for x in (32,97):
            d.ellipse((x-15,7,x+1,23),fill=1)
            d.ellipse((x-1,7,x+15,23),fill=1)
            d.polygon([(x-15,17),(x+15,17),(x,36)],fill=1)
        smile()
    elif name == 'cheeky':
        eye(19)
        d.arc((83,11,111,33),180,360,fill=1,width=5)
        smile()
        d.rounded_rectangle((65,48,78,61),radius=5,fill=1)
    return im

def main():
    faces=[face(n) for n in NAMES]
    header=['// Generated by scripts/build_faces.py; edit the pixel drawings there.',
            '#pragma once', '#include <pgmspace.h>', 'namespace lesson {',
            'constexpr int FACE_COUNT=7;',
            'inline const char *faceName(int n) {',
            '  static const char *names[]={"AWAKE","HAPPY","SLEEP","CURIOUS","SURPRISED","LOVE","CHEEKY"};',
            '  return n>=0 && n<FACE_COUNT ? names[n] : "CLEAR";', '}',
            'const uint8_t FACE_BITMAPS[FACE_COUNT][1024] PROGMEM = {']
    for name,im in zip(NAMES,faces):
        data=im.tobytes()  # row-major, MSB first: Adafruit_GFX drawBitmap format
        assert len(data)==1024
        header.append('  { // '+name)
        for i in range(0,len(data),16):
            header.append('    '+','.join(f'0x{x:02x}' for x in data[i:i+16])+',')
        header.append('  },')
    header+=['};','}']
    (ROOT/'lessons/lib/RobotLessons/src/FaceArt.h').write_text('\n'.join(header)+'\n',encoding='utf-8')
    gallery=Image.new('RGB',(1120,340),'#172432')
    for i,im in enumerate(faces):
        gallery.paste(im.convert('RGB').resize((256,128),Image.Resampling.NEAREST),
                      (12+(i%4)*280,20+(i//4)*170))
    destination=ROOT/'docs/faces'
    destination.mkdir(exist_ok=True)
    gallery.save(destination/'face-gallery.png')
    print('Generated seven 128x64 face bitmaps and matching gallery.')

if __name__ == '__main__':
    main()
